#!/usr/bin/env node
/**
 * OpenClaw Use Case Hunter
 * Searches the web for interesting OpenClaw setups, automations, and use cases
 * Creates kanban ideas from noteworthy findings
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const SEARCH_QUERIES = [
  'openclaw.ai use cases automations',
  'clawhub.com skills agents',
  'openclaw discord setups',
  'openclaw github examples',
];

const SEEN_FILE = '/tmp/openclaw_hunter_seen.txt';
let dedup = { knownTitles: new Set(), knownUrls: new Set(), knownRepos: new Set() };

// ─────────────────────────────────────────
// Load dedup sets from ALL kanban folders
// ─────────────────────────────────────────
function loadKanbanDedup() {
  const kanbanDir = '/home/john/.openclaw/workspace/kanban';
  const knownTitles = new Set();
  const knownUrls = new Set();
  const knownRepos = new Set();

  for (const dir of ['idea', 'complete', 'done', 'rejected']) {
    const dirPath = path.join(kanbanDir, dir);
    let files;
    try {
      files = fs.readdirSync(dirPath).filter(f => f.endsWith('.md'));
    } catch {
      continue;
    }
    for (const file of files) {
      const content = fs.readFileSync(path.join(dirPath, file), 'utf8');
      // Extract title
      const titleMatch = content.match(/\*\*Title:\*\*\s*(.+)/i);
      if (titleMatch) knownTitles.add(titleMatch[1].trim().toLowerCase());
      // Extract URL
      const urlMatch = content.match(/## URL\n(.+)/i);
      if (urlMatch && urlMatch[1].trim()) knownUrls.add(urlMatch[1].trim().toLowerCase());
      // Extract GitHub repo
      const repoMatch = content.match(/GitHub:\s*([^\s|]+(?:\/[^\s|]+)?)/i);
      if (repoMatch) knownRepos.add(repoMatch[1].trim().toLowerCase());
    }
  }
  return { knownTitles, knownUrls, knownRepos };
}

function isDuplicate(title, url, repo) {
  const titleNorm = (title || '').toLowerCase().trim();
  const urlNorm = (url || '').toLowerCase().trim();
  const repoNorm = (repo || '').toLowerCase().trim();

  if (urlNorm && dedup.knownUrls.has(urlNorm)) return `URL already seen: ${urlNorm}`;
  if (titleNorm && dedup.knownTitles.has(titleNorm)) return `Title already exists: ${titleNorm}`;
  if (repoNorm && dedup.knownRepos.has(repoNorm)) return `Repo already exists: ${repoNorm}`;
  return null;
}

function searchWeb(query) {
  try {
    const result = execSync(
      `node /home/john/.openclaw/workspace/scripts/websearch.js "${query.replace(/"/g, '\\"')}" 2>&1`,
      { timeout: 30000, encoding: 'utf8' }
    );
    return result;
  } catch (e) {
    return '';
  }
}

function loadSeen() {
  try {
    return new Set(fs.readFileSync(SEEN_FILE, 'utf8').split('\n').filter(Boolean));
  } catch {
    return new Set();
  }
}

function saveSeen(seen) {
  fs.writeFileSync(SEEN_FILE, [...seen].join('\n'));
}

function createIdea(title, summary, why) {
  try {
    const id = 'IDEA-' + Date.now().toString().slice(-4);
    const file = `/home/john/.openclaw/workspace/kanban/idea/${id}-${title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.md`;
    const content = `# Idea
**ID:** ${id}
**Title:** ${title}
**Status:** Pending Review
**Suggested Priority:** Medium
**Source:** Use Case Hunter
**Created:** ${new Date().toISOString().slice(0, 16).replace('T', ' ')}

## Summary
${summary}

## Why It Might Matter
${why}

## Approval Decision
Pending Review

## Notes
Auto-generated by openclaw-use-case-hunter.js
`;
    fs.writeFileSync(file, content);
    console.log(`Created: ${file}`);
    return true;
  } catch (e) {
    console.error(`Failed to create idea: ${e.message}`);
    return false;
  }
}

function extractUrls(text) {
  const matches = text.match(/https?:\/\/[^\s<>"\]]+/g) || [];
  return [...new Set(matches)].slice(0, 5);
}

async function main() {
  const seen = loadSeen();
  dedup = loadKanbanDedup();
  let newFindings = 0;

  for (const query of SEARCH_QUERIES) {
    console.log(`Searching: ${query}`);
    const results = searchWeb(query);
    const urls = extractUrls(results);

    for (const url of urls) {
      if (seen.has(url)) continue;
      seen.add(url);

      // Skip if no useful content in result
      if (results.length < 50) continue;

      // Look for interesting OpenClaw patterns
      const lines = results.split('\n').filter(l => l.includes(url) || l.length > 100);

      // Create ideas for things that look like real setups/use cases
      for (const line of lines) {
        if (
          (line.includes('skill') || line.includes('automation') || line.includes('setup') || line.includes('workflow')) &&
          line.length > 80 &&
          line.length < 500
        ) {
          // Extract a title from the line
          const clean = line.replace(/https?:\/\/[^\s]+/g, '').replace(/[*#]/g, '').trim();
          if (clean.length > 20 && clean.length < 200) {
            const title = clean.slice(0, 80).replace(/\n/g, ' ').trim();
            const summary = `Discovered: ${clean.slice(0, 300)} Source: ${url}`;
            const why = 'Found via automated use case hunting - review for potential value to ARR stack or OpenClaw setup';

            // Skip if already in kanban (any folder)
            const dupReason = isDuplicate(title, url, null);
            if (dupReason) {
              console.log(`Skipped duplicate: ${dupReason}`);
              continue;
            }

            if (createIdea(title, summary, why)) {
              newFindings++;
              await new Promise(r => setTimeout(r, 500)); // rate limit
            }
            break;
          }
        }
      }
    }
  }

  saveSeen(seen);
  console.log(`\nDone. New ideas created: ${newFindings}`);
}

main().catch(console.error);
